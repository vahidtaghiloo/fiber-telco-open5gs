#!/usr/bin/env python3
"""Derive bench-v2/platform/vms/telco-cluster-calico.yaml from platform/vms/telco-cluster.yaml.

The original file is only read. Changes (each is asserted, the script fails if the original changed shape):
  1. k3s server:  --flannel-iface $IF  ->  --flannel-backend=none --disable-network-policy
  2. k3s agents:  --flannel-iface $IF  ->  (removed; the server's setting applies)
  3. server bootstrap: install Calico (Tigera operator, VXLAN, pool 10.42.0.0/16, node address taken from the net1 subnet
     10.20.0.0/24) BEFORE waiting for the node to become Ready (without a CNI it never would)
  4. server bootstrap: no Flux install / sync. The benchmark deploys both variants with the same `helm template | kubectl apply`.
Names, sizes, MACs and IPs are unchanged, so this file REPLACES the original VMs (it cannot run next to them).
usage: python3 bench-v2/tools/make_calico_variant.py
"""
import pathlib, sys

root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "platform/vms/telco-cluster.yaml").read_text()
dst = root / "bench-v2/platform/vms/telco-cluster-calico.yaml"
CALICO_VERSION = "v3.29.3"   # keep in step with the Calico version of the Sylva workload cluster (README section 5.2)

def sub(text, old, new, count):
    assert text.count(old) == count, f"expected {count}x {old!r}, found {text.count(old)}x"
    return text.replace(old, new)

out = src
out = sub(out, "server $NODEIP --flannel-iface $IF \\",
          "server $NODEIP --flannel-backend=none --disable-network-policy \\", 1)
out = sub(out, "agent $NODEIP --flannel-iface $IF \\", "agent $NODEIP \\", 2)

I = " " * 10   # indentation of the bootstrap script inside the cloud-config
calico = f"""export KUBECONFIG=/etc/rancher/k3s/k3s.yaml
{I}until k3s kubectl get ns >/dev/null 2>&1; do sleep 3; done
{I}# Calico (Tigera operator), the same CNI as the Sylva workload cluster. VXLAN over net1 (the rented VLAN 300 slice).
{I}k3s kubectl create -f https://raw.githubusercontent.com/projectcalico/calico/{CALICO_VERSION}/manifests/tigera-operator.yaml
{I}until k3s kubectl get crd installations.operator.tigera.io >/dev/null 2>&1; do sleep 3; done
{I}sleep 10
{I}cat <<'EOF3' | k3s kubectl apply -f -
{I}apiVersion: operator.tigera.io/v1
{I}kind: Installation
{I}metadata: {{name: default}}
{I}spec:
{I}  calicoNetwork:
{I}    containerIPForwarding: Enabled
{I}    bgp: Disabled
{I}    ipPools:
{I}    - {{cidr: 10.42.0.0/16, encapsulation: VXLAN, natOutgoing: Enabled, nodeSelector: all()}}
{I}    nodeAddressAutodetectionV4: {{cidrs: ["10.20.0.0/24"]}}
{I}EOF3
"""
out = sub(out, f"export KUBECONFIG=/etc/rancher/k3s/k3s.yaml\n{I}until k3s kubectl get nodes 2>/dev/null | grep -q ' Ready'; do sleep 5; done\n",
          calico + f"{I}until k3s kubectl get nodes 2>/dev/null | grep -q ' Ready'; do sleep 5; done\n", 1)

# drop the Flux install + sync (4 lines)
flux = (f"{I}k3s kubectl apply -f https://github.com/fluxcd/flux2/releases/download/v2.8.8/install.yaml\n"
        f"{I}until k3s kubectl get crd gitrepositories.source.toolkit.fluxcd.io 2>/dev/null; do sleep 5; done\n"
        f"{I}sleep 15\n"
        f"{I}k3s kubectl apply -f /root/flux-sync.yaml\n")
out = sub(out, flux, f"{I}# (no Flux in bench-v2: Open5GS is deployed with helm template, as in the direct variant)\n", 1)

header = ("# GENERATED by bench-v2/tools/make_calico_variant.py from platform/vms/telco-cluster.yaml. Do not edit by hand.\n"
          "# bench-v2 variant: the telco's k3s uses CALICO (VXLAN over net1) instead of flannel, like the Sylva workload cluster,\n"
          "# and has no Flux. Everything else (VM sizes, MACs, IPs, secrets) is identical to the original.\n")
dst.write_text(header + out)
print("wrote", dst)
